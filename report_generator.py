import os

def ensure_reports_folder():
    reports_dir = "reports"

    if os.path.exists(reports_dir) and not os.path.isdir(reports_dir):
        os.remove(reports_dir)

    os.makedirs(reports_dir, exist_ok=True)

    return reports_dir


