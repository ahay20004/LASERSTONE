const learningButtons = Array.from(document.querySelectorAll('.learning-step'));
const learningReadout = document.getElementById('learning-readout');
const learningCount = document.getElementById('learning-count');
const learningPrev = document.getElementById('learning-prev');
const learningNext = document.getElementById('learning-next');
let learningIndex = 0;
function updateLearning(lang) {
  if (!learningReadout) return;
  const messages = translations[lang] || translations.en;
  learningReadout.querySelector('strong').textContent = messages['learningStep' + learningIndex];
  learningReadout.querySelector('p').textContent = messages['learningDesc' + learningIndex];
  document.getElementById('example-stage-title').textContent = messages['exampleStageTitle' + learningIndex];
  document.getElementById('example-stage-detail').textContent = messages['exampleStageDetail' + learningIndex];
  learningButtons.forEach((button, index) => {
    const active = index === learningIndex;
    button.setAttribute('aria-pressed', String(active));
    button.classList.toggle('is-current', active);
  });
  learningCount.textContent = (learningIndex + 1) + ' / ' + learningButtons.length;
  learningPrev.disabled = learningIndex === 0;
  learningNext.disabled = learningIndex === learningButtons.length - 1;
}
learningButtons.forEach((button, index) => button.addEventListener('click', () => {
  learningIndex = index;
  updateLearning(document.documentElement.lang);
}));
learningPrev.addEventListener('click', () => {
  learningIndex = Math.max(0, learningIndex - 1);
  updateLearning(document.documentElement.lang);
});
learningNext.addEventListener('click', () => {
  learningIndex = Math.min(learningButtons.length - 1, learningIndex + 1);
  updateLearning(document.documentElement.lang);
});
/* Bounded classroom calculator: fixed ranges, no remote execution or user data. */
const labAlpha = document.getElementById('lab-alpha');
const labDepth = document.getElementById('lab-depth');
const labWavelength = document.getElementById('lab-wavelength');
const labIncident = document.getElementById('lab-incident');
const teachingAlpha = Object.freeze({'532': 0.8, '632.8': 0.5, '1064': 0.2});
function updateAttenuation() {
  if (!labAlpha || !labDepth) return;
  const alpha = Number(labAlpha.value);
  const depth = Number(labDepth.value);
  const ratio = Math.exp(-alpha * depth);
  const incident = Number(labIncident.value);
  document.getElementById('lab-incident-value').textContent = incident.toFixed(1);
  document.getElementById('lab-absolute').textContent = (incident * ratio).toFixed(3) + ' mW/cm²';
  document.getElementById('lab-alpha-value').textContent = alpha.toFixed(2);
  document.getElementById('lab-depth-value').textContent = depth.toFixed(1);
  document.getElementById('lab-ratio').textContent = ratio.toFixed(4);
  document.getElementById('lab-percent').textContent = (ratio * 100).toFixed(2) + '%';
  document.getElementById('lab-bar').style.width = (ratio * 100).toFixed(2) + '%';
}
if (labAlpha && labDepth) {
  labAlpha.addEventListener('input', updateAttenuation);
  labDepth.addEventListener('input', updateAttenuation);
  labIncident.addEventListener('input', updateAttenuation);
  labWavelength.addEventListener('change', () => {
    labAlpha.value = String(teachingAlpha[labWavelength.value]);
    updateAttenuation();
  });
}
applyLanguage(requested);
updateAttenuation();

